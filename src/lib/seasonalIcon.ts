/* ═══════════════════════════════════════════════════════════════════════
   The tab icon follows the season an admin schedules (Christmas, Sallah,
   Independence Day...) — the backend's seasonService.js. The icons are in
   public/seasonal/, generated by brand/seasonal-icons/generate.mjs.

   Only the browser tab and the iOS home-screen icon change at once; an
   installed Android web app keeps its manifest icon until Chrome next
   refreshes it.
   ═══════════════════════════════════════════════════════════════════════ */

import { API_BASE as API } from './http'

const KNOWN = new Set(['christmas', 'newyear', 'valentine', 'easter', 'sallah', 'independence', 'school'])

export async function startSeasonalIcon(): Promise<void> {
  try {
    const res = await fetch(`${API}/api/seasons/active?app=vendor`)
    if (!res.ok) return
    const season = (await res.json())?.data?.season
    if (typeof season !== 'string' || !KNOWN.has(season)) return
    document.querySelectorAll<HTMLLinkElement>('link[rel="icon"]').forEach((link) => {
      link.type = 'image/png'
      link.href = `/seasonal/${season}.png`
    })
    document.querySelectorAll<HTMLLinkElement>('link[rel="apple-touch-icon"]').forEach((link) => {
      link.href = `/seasonal/${season}-192.png`
    })
  } catch {
    // Offline or blocked: the usual icon stays.
  }
}
